"""Generate the list of toolkit CLI command paths (E-007).

``tools/cli_commands.json`` names every command a user can type after ``specdev``: the
top-level commands, the sub-commands of groups that declare sub-parsers (``context``), the
positional ``choices`` of ``align``, and the sub-commands of REMAINDER passthrough groups
whose real parser lives elsewhere (``json``, ``node``).  Paths only; flags are not listed.

``PASSTHROUGH_BUILDERS`` maps a passthrough group to the zero-argument builder of its own
parser.  Later milestones add one entry per further passthrough group.
"""
from __future__ import annotations

import argparse
from typing import Callable, Mapping

from specdev_tools.core.json_utils import build_json_parser
from specdev_tools.graph.commands import build_node_parser

FORMAT_VERSION = "1.0.0"
NOTE = (
    "Generated by 'specdev registry-generate' from the CLI argparse parsers. "
    "Do not hand-edit; consumers should not parse this string."
)

# Groups whose sub-commands are positional ``choices`` (not sub-parsers): group -> positional dest.
CHOICE_GROUPS: dict[str, str] = {"align": "action"}

# REMAINDER passthrough groups: group -> builder of the parser that owns the sub-commands.
PASSTHROUGH_BUILDERS: dict[str, Callable[[], argparse.ArgumentParser]] = {"json": build_json_parser, "node": build_node_parser}


def _subparser_choices(parser: argparse.ArgumentParser) -> dict[str, argparse.ArgumentParser]:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return dict(action.choices)
    return {}


def collect_command_paths(
    parser: argparse.ArgumentParser,
    passthrough: Mapping[str, Callable[[], argparse.ArgumentParser]] | None = None,
) -> list[str]:
    """Return the sorted command paths of ``parser`` (top-level, sub-commands, actions)."""
    passthrough = PASSTHROUGH_BUILDERS if passthrough is None else passthrough
    paths: set[str] = set()
    for name, sub in _subparser_choices(parser).items():
        paths.add(name)
        for child in _subparser_choices(sub):
            paths.add(f"{name} {child}")
        dest = CHOICE_GROUPS.get(name)
        if dest:
            for action in sub._actions:
                if action.dest == dest and action.choices:
                    paths.update(f"{name} {c}" for c in action.choices)
        if name in passthrough:
            for child in _subparser_choices(passthrough[name]()):
                paths.add(f"{name} {child}")
    return sorted(paths)


def generate_cli_commands(
    passthrough: Mapping[str, Callable[[], argparse.ArgumentParser]] | None = None,
) -> dict:
    """Build the ``vc:cli-commands`` document from the live CLI parsers."""
    from specdev_tools.cli import build_parser

    return {
        "$schema": "vc:cli-commands",
        "_format_version": FORMAT_VERSION,
        "_note": NOTE,
        "commands": [{"path": p} for p in collect_command_paths(build_parser(), passthrough)],
    }
